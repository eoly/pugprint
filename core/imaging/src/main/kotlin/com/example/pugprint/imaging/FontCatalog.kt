                    'J' to Glyph.of("..###", "...#.", "...#.", "...#.", "...#.", "#..#.", ".##.."),
                    'K' to Glyph.of("#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#"),
                    'L' to Glyph.of("#....", "#....", "#....", "#....", "#....", "#....", "#####"),
                    'M' to Glyph.of("#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#"),
                    'N' to Glyph.of("#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#", "#...#"),
                    'O' to Glyph.of(".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."),
                    'P' to Glyph.of("####.", "#...#", "#...#", "####.", "#....", "#....", "#...."),
                    'Q' to Glyph.of(".###.", "#...#", "#...#", "#...#", "#.#.#", "#..#.", ".##.#"),
                    'R' to Glyph.of("####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"),
                    'S' to Glyph.of(".####", "#....", "#....", ".###.", "....#", "....#", "####."),
                    'T' to Glyph.of("#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."),
