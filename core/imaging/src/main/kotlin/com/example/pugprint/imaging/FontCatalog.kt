                    'W' to Glyph.of("#...#", "#...#", "#...#", "#.#.#", "#.#.#", "##.##", "#...#"),
                    'X' to Glyph.of("#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#"),
                    'Y' to Glyph.of("#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#.."),
                    'Z' to Glyph.of("#####", "....#", "...#.", "..#..", ".#...", "#....", "#####"),
                    '0' to Glyph.of(".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###."),
                    '1' to Glyph.of("..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###."),
