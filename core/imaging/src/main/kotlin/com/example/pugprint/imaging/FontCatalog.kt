package com.example.pugprint.imaging

/**
 * Every typeface a caption can use. **To add a font, add one [PixelFont] to [all]** and draw its
 * letters as rows of `#` and `.` — every glyph the same height, any width. `FontCatalogTest`
 * checks the rules and `TextRasterizerTest` records a golden picture per font.
 */
public object FontCatalog {
    /** The classic 5 × 7 dot font: sturdy at any size. */
    public val Blocky: PixelFont =
        PixelFont(
            id = "blocky",
            displayName = "Blocky",
            glyphHeight = 7,
            fallback = Glyph.of("#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"),
            glyphs =
                mapOf(
                    ' ' to Glyph.of("...", "...", "...", "...", "...", "...", "..."),
                    'A' to Glyph.of(".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"),
                    'B' to Glyph.of("####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."),
                    'C' to Glyph.of(".###.", "#...#", "#....", "#....", "#....", "#...#", ".###."),
                    'D' to Glyph.of("####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####."),
                    'E' to Glyph.of("#####", "#....", "#....", "####.", "#....", "#....", "#####"),
                    'F' to Glyph.of("#####", "#....", "#....", "####.", "#....", "#....", "#...."),
                    'G' to Glyph.of(".###.", "#...#", "#....", "#.###", "#...#", "#...#", ".####"),
