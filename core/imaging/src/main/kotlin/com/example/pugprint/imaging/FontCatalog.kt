                ),
        )

    /** In picker order. */
    public val all: List<PixelFont> = listOf(Blocky)

    public val default: PixelFont = Blocky

    /** The font saved under [id], or [default] if the id is unknown. */
    public fun byId(id: String?): PixelFont = all.firstOrNull { it.id == id } ?: default
}
